create schema if not exists alumnos;

-- ------------------------------------------------------------
-- Catálogo académico
-- ------------------------------------------------------------
create table if not exists alumnos.niveles (
  id smallint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text
);

create table if not exists alumnos.grados (
  id bigint generated by default as identity primary key,
  nivel_id smallint not null,
  nombre text not null,
  orden smallint not null check (orden > 0),
  constraint grados_nivel_fk foreign key (nivel_id)
    references alumnos.niveles(id) on update cascade on delete restrict,
  constraint grados_nivel_nombre_uk unique (nivel_id, nombre),
  constraint grados_nivel_orden_uk unique (nivel_id, orden)
);

create table if not exists alumnos.aulas (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  capacidad smallint not null check (capacidad > 0),
  ubicacion text
);

-- ------------------------------------------------------------
-- Personas
-- ------------------------------------------------------------
create table if not exists alumnos.tutores (
  id bigint generated by default as identity primary key,
  nombre text not null,
  apellido text not null,
  parentesco text,
  email text,
  telefono text,
  direccion text
);

create table if not exists alumnos.profesores (
  id bigint generated by default as identity primary key,
  nombre text not null,
  apellido text not null,
  email text not null unique,
  telefono text,
  especialidad text,
  fecha_ingreso date,
  activo boolean not null default true
);

create table if not exists alumnos.alumnos (
  id bigint generated by default as identity primary key,
  matricula text not null unique,
  nombre text not null,
  apellido text not null,
  fecha_nacimiento date,
  email text unique,
  telefono text,
  direccion text,
  grado_id bigint not null,
  aula_id bigint,
  fecha_inscripcion date not null default current_date,
  activo boolean not null default true,
  constraint alumnos_grado_fk foreign key (grado_id)
    references alumnos.grados(id) on update cascade on delete restrict,
  constraint alumnos_aula_fk foreign key (aula_id)
    references alumnos.aulas(id) on update cascade on delete set null
);

create table if not exists alumnos.alumno_tutor (
  alumno_id bigint not null,
  tutor_id bigint not null,
  es_principal boolean not null default false,
  constraint alumno_tutor_pk primary key (alumno_id, tutor_id),
  constraint alumno_tutor_alumno_fk foreign key (alumno_id)
    references alumnos.alumnos(id) on update cascade on delete cascade,
  constraint alumno_tutor_tutor_fk foreign key (tutor_id)
    references alumnos.tutores(id) on update cascade on delete cascade
);

-- Un alumno solo puede tener un tutor principal
create unique index if not exists alumno_tutor_principal_uk
  on alumnos.alumno_tutor (alumno_id)
  where es_principal;

-- ------------------------------------------------------------
-- Gestión académica
-- ------------------------------------------------------------
create table if not exists alumnos.materias (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  creditos smallint not null default 1 check (creditos > 0)
);

create table if not exists alumnos.materia_nivel (
  materia_id bigint not null,
  nivel_id smallint not null,
  constraint materia_nivel_pk primary key (materia_id, nivel_id),
  constraint materia_nivel_materia_fk foreign key (materia_id)
    references alumnos.materias(id) on update cascade on delete cascade,
  constraint materia_nivel_nivel_fk foreign key (nivel_id)
    references alumnos.niveles(id) on update cascade on delete cascade
);

create table if not exists alumnos.cursos (
  id bigint generated by default as identity primary key,
  materia_id bigint not null,
  profesor_id bigint not null,
  grado_id bigint not null,
  aula_id bigint,
  ciclo_escolar text not null,
  seccion text not null default 'A',
  capacidad smallint not null default 30 check (capacidad > 0),
  constraint cursos_materia_fk foreign key (materia_id)
    references alumnos.materias(id) on update cascade on delete restrict,
  constraint cursos_profesor_fk foreign key (profesor_id)
    references alumnos.profesores(id) on update cascade on delete restrict,
  constraint cursos_grado_fk foreign key (grado_id)
    references alumnos.grados(id) on update cascade on delete restrict,
  constraint cursos_aula_fk foreign key (aula_id)
    references alumnos.aulas(id) on update cascade on delete set null,
  constraint cursos_oferta_uk unique (materia_id, grado_id, ciclo_escolar, seccion)
);

create table if not exists alumnos.inscripciones (
  id bigint generated by default as identity primary key,
  alumno_id bigint not null,
  curso_id bigint not null,
  fecha_inscripcion date not null default current_date,
  estado text not null default 'activa' check (estado in ('activa','retirada','completada')),
  constraint inscripciones_alumno_fk foreign key (alumno_id)
    references alumnos.alumnos(id) on update cascade on delete cascade,
  constraint inscripciones_curso_fk foreign key (curso_id)
    references alumnos.cursos(id) on update cascade on delete cascade,
  constraint inscripciones_alumno_curso_uk unique (alumno_id, curso_id)
);

create table if not exists alumnos.horarios (
  id bigint generated by default as identity primary key,
  curso_id bigint not null,
  dia_semana smallint not null check (dia_semana between 1 and 7), -- 1=lunes, 7=domingo
  hora_inicio time not null,
  hora_fin time not null,
  salon text,
  constraint horarios_curso_fk foreign key (curso_id)
    references alumnos.cursos(id) on update cascade on delete cascade,
  constraint horarios_rango_ck check (hora_fin > hora_inicio),
  constraint horarios_curso_dia_hora_uk unique (curso_id, dia_semana, hora_inicio)
);

-- ------------------------------------------------------------
-- Evaluación
-- ------------------------------------------------------------
create table if not exists alumnos.calificaciones (
  id bigint generated by default as identity primary key,
  inscripcion_id bigint not null,
  evaluacion text not null,
  calificacion numeric(4,2) not null check (calificacion between 0 and 10), -- escala 0-10
  fecha_evaluacion date not null default current_date,
  observaciones text,
  constraint calificaciones_inscripcion_fk foreign key (inscripcion_id)
    references alumnos.inscripciones(id) on update cascade on delete cascade,
  constraint calificaciones_inscripcion_eval_uk unique (inscripcion_id, evaluacion)
);

create table if not exists alumnos.asistencias (
  id bigint generated by default as identity primary key,
  inscripcion_id bigint not null,
  fecha date not null,
  estado text not null check (estado in ('presente','ausente','tarde','justificada')),
  observaciones text,
  constraint asistencias_inscripcion_fk foreign key (inscripcion_id)
    references alumnos.inscripciones(id) on update cascade on delete cascade,
  constraint asistencias_inscripcion_fecha_uk unique (inscripcion_id, fecha)
);

-- ------------------------------------------------------------
-- Finanzas
-- ------------------------------------------------------------
create table if not exists alumnos.pagos (
  id bigint generated by default as identity primary key,
  alumno_id bigint not null,
  ciclo_escolar text not null,
  concepto text not null,
  monto numeric(10,2) not null check (monto >= 0),
  fecha_vencimiento date,
  fecha_pago date,
  metodo_pago text check (metodo_pago in ('efectivo','transferencia','tarjeta','otro')),
  estado text not null default 'pendiente' check (estado in ('pendiente','pagado','cancelado')),
  referencia text,
  constraint pagos_alumno_fk foreign key (alumno_id)
    references alumnos.alumnos(id) on update cascade on delete cascade,
  constraint pagos_pagado_fecha_ck check (estado <> 'pagado' or fecha_pago is not null)
);

-- ------------------------------------------------------------
-- Índices
-- ------------------------------------------------------------
create index if not exists grados_nivel_idx on alumnos.grados(nivel_id);
create index if not exists alumnos_grado_idx on alumnos.alumnos(grado_id);
create index if not exists alumnos_aula_idx on alumnos.alumnos(aula_id);
create index if not exists alumno_tutor_tutor_idx on alumnos.alumno_tutor(tutor_id);
create index if not exists materia_nivel_nivel_idx on alumnos.materia_nivel(nivel_id);
create index if not exists cursos_materia_idx on alumnos.cursos(materia_id);
create index if not exists cursos_profesor_idx on alumnos.cursos(profesor_id);
create index if not exists cursos_grado_idx on alumnos.cursos(grado_id);
create index if not exists cursos_aula_idx on alumnos.cursos(aula_id);
create index if not exists inscripciones_alumno_idx on alumnos.inscripciones(alumno_id);
create index if not exists inscripciones_curso_idx on alumnos.inscripciones(curso_id);
create index if not exists horarios_curso_idx on alumnos.horarios(curso_id);
create index if not exists calificaciones_inscripcion_idx on alumnos.calificaciones(inscripcion_id);
create index if not exists asistencias_inscripcion_idx on alumnos.asistencias(inscripcion_id);
create index if not exists pagos_alumno_idx on alumnos.pagos(alumno_id);
create index if not exists pagos_estado_idx on alumnos.pagos(estado);

