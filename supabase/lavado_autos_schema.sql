-- Esquema `lavado_autos`: sistema de gestión para un negocio de lavado de autos.
-- Ejecutar en Supabase (SQL Editor) o con: psql "$DATABASE_URL" -f lavado_autos_schema.sql

create schema if not exists lavado_autos;

-- ---------------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------------

create table if not exists lavado_autos.clientes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  apellido text not null,
  telefono text not null unique,
  email text unique,
  direccion text,
  fecha_registro date not null default current_date,
  activo boolean not null default true
);

create table if not exists lavado_autos.vehiculos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null,
  placa text not null unique,
  marca text not null,
  modelo text not null,
  anio smallint not null check (anio between 1980 and 2035),
  color text,
  tipo text not null default 'sedan' check (tipo in ('sedan','suv','pickup','moto','van')),
  creado_en timestamptz not null default now(),
  constraint vehiculos_cliente_fk foreign key (cliente_id)
    references lavado_autos.clientes(id) on update cascade on delete restrict
);

create table if not exists lavado_autos.servicios (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  precio numeric(10,2) not null check (precio >= 0),
  duracion_min smallint not null check (duracion_min > 0),
  activo boolean not null default true
);

create table if not exists lavado_autos.empleados (
  id bigint generated by default as identity primary key,
  nombre text not null,
  apellido text not null,
  puesto text not null check (puesto in ('lavador','supervisor','cajero','recepcionista','gerente')),
  telefono text,
  email text unique,
  fecha_ingreso date,
  activo boolean not null default true
);

create table if not exists lavado_autos.insumos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  unidad text not null check (unidad in ('litro','kilo','pieza')),
  stock numeric(10,2) not null default 0 check (stock >= 0),
  stock_minimo numeric(10,2) not null default 0 check (stock_minimo >= 0),
  costo_unitario numeric(10,2) not null check (costo_unitario >= 0)
);

create table if not exists lavado_autos.promociones (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descuento_pct numeric(5,2) not null check (descuento_pct between 0 and 100),
  fecha_inicio date not null,
  fecha_fin date not null,
  activo boolean not null default true,
  constraint promociones_fechas_ck check (fecha_fin >= fecha_inicio)
);

-- ---------------------------------------------------------------------------
-- Operación
-- ---------------------------------------------------------------------------

create table if not exists lavado_autos.citas (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null,
  vehiculo_id bigint not null,
  fecha_hora timestamptz not null,
  estado text not null default 'pendiente' check (estado in ('pendiente','confirmada','atendida','cancelada','no_asistio')),
  notas text,
  constraint citas_cliente_fk foreign key (cliente_id)
    references lavado_autos.clientes(id) on update cascade on delete cascade,
  constraint citas_vehiculo_fk foreign key (vehiculo_id)
    references lavado_autos.vehiculos(id) on update cascade on delete cascade
);

create table if not exists lavado_autos.ordenes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null,
  vehiculo_id bigint not null,
  empleado_id bigint not null,
  fecha timestamptz not null default now(),
  estado text not null default 'abierta' check (estado in ('abierta','en_proceso','terminada','pagada','cancelada')),
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  descuento numeric(10,2) not null default 0 check (descuento >= 0),
  total numeric(10,2) not null default 0 check (total >= 0),
  observaciones text,
  constraint ordenes_cliente_fk foreign key (cliente_id)
    references lavado_autos.clientes(id) on update cascade on delete restrict,
  constraint ordenes_vehiculo_fk foreign key (vehiculo_id)
    references lavado_autos.vehiculos(id) on update cascade on delete restrict,
  constraint ordenes_empleado_fk foreign key (empleado_id)
    references lavado_autos.empleados(id) on update cascade on delete restrict,
  constraint ordenes_total_ck check (total <= subtotal)
);

create table if not exists lavado_autos.orden_detalle (
  id bigint generated by default as identity primary key,
  orden_id bigint not null,
  servicio_id bigint not null,
  cantidad smallint not null default 1 check (cantidad > 0),
  precio_unitario numeric(10,2) not null check (precio_unitario >= 0),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  constraint orden_detalle_orden_fk foreign key (orden_id)
    references lavado_autos.ordenes(id) on update cascade on delete cascade,
  constraint orden_detalle_servicio_fk foreign key (servicio_id)
    references lavado_autos.servicios(id) on update cascade on delete restrict,
  constraint orden_detalle_orden_servicio_uk unique (orden_id, servicio_id)
);

create table if not exists lavado_autos.pagos (
  id bigint generated by default as identity primary key,
  orden_id bigint not null,
  monto numeric(10,2) not null check (monto > 0),
  metodo text not null check (metodo in ('efectivo','tarjeta','transferencia','wallet')),
  fecha_pago timestamptz,
  referencia text,
  estado text not null default 'aprobado' check (estado in ('aprobado','pendiente','rechazado')),
  constraint pagos_orden_fk foreign key (orden_id)
    references lavado_autos.ordenes(id) on update cascade on delete cascade,
  constraint pagos_aprobado_fecha_ck check (estado <> 'aprobado' or fecha_pago is not null)
);

create table if not exists lavado_autos.consumo_insumos (
  id bigint generated by default as identity primary key,
  orden_id bigint not null,
  insumo_id bigint not null,
  cantidad numeric(10,2) not null check (cantidad > 0),
  fecha timestamptz not null default now(),
  constraint consumo_insumos_orden_fk foreign key (orden_id)
    references lavado_autos.ordenes(id) on update cascade on delete cascade,
  constraint consumo_insumos_insumo_fk foreign key (insumo_id)
    references lavado_autos.insumos(id) on update cascade on delete restrict,
  constraint consumo_insumos_orden_insumo_uk unique (orden_id, insumo_id)
);

create table if not exists lavado_autos.orden_promociones (
  orden_id bigint not null,
  promocion_id bigint not null,
  constraint orden_promociones_pk primary key (orden_id, promocion_id),
  constraint orden_promociones_orden_fk foreign key (orden_id)
    references lavado_autos.ordenes(id) on update cascade on delete cascade,
  constraint orden_promociones_promo_fk foreign key (promocion_id)
    references lavado_autos.promociones(id) on update cascade on delete restrict
);

-- ---------------------------------------------------------------------------
-- Índices para claves foráneas y consultas frecuentes
-- ---------------------------------------------------------------------------

create index if not exists vehiculos_cliente_idx on lavado_autos.vehiculos(cliente_id);
create index if not exists citas_cliente_idx on lavado_autos.citas(cliente_id);
create index if not exists citas_vehiculo_idx on lavado_autos.citas(vehiculo_id);
create index if not exists ordenes_cliente_idx on lavado_autos.ordenes(cliente_id);
create index if not exists ordenes_vehiculo_idx on lavado_autos.ordenes(vehiculo_id);
create index if not exists ordenes_empleado_idx on lavado_autos.ordenes(empleado_id);
create index if not exists orden_detalle_orden_idx on lavado_autos.orden_detalle(orden_id);
create index if not exists orden_detalle_servicio_idx on lavado_autos.orden_detalle(servicio_id);
create index if not exists pagos_orden_idx on lavado_autos.pagos(orden_id);
create index if not exists consumo_insumos_orden_idx on lavado_autos.consumo_insumos(orden_id);
create index if not exists consumo_insumos_insumo_idx on lavado_autos.consumo_insumos(insumo_id);
create index if not exists orden_promociones_promo_idx on lavado_autos.orden_promociones(promocion_id);

